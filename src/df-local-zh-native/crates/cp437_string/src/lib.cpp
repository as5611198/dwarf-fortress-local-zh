// Inline helper to cast void* to string*
static inline const string *sp(const void *ptr)
{
  return (string *)(ptr);
}

// Get the size of the string pointed to by ptr
extern "C" size_t string_size(const void *ptr)
{
  return sp(ptr)->size();
}

// Convert a CP437 encoded C-style string by ptr to a UTF-8 encoded slice
extern "C" size_t cp437_cstr_ptr_to_utf8_slice(const char *ptr, char *utf8_slice)
{
  char *p = utf8_slice;

  for (size_t i = 0; ptr[i] != '\0'; i++)
  {
    uint8_t cp437_ch = static_cast<uint8_t>(ptr[i]);
    uint32_t utf8_len = cp437_to_utf8_table[cp437_ch * 2];
    uint32_t utf8_bytes = cp437_to_utf8_table[cp437_ch * 2 + 1];

    *(uint32_t *)(p) = utf8_bytes;
    p += utf8_len;
  }

  return static_cast<size_t>(p - utf8_slice);
}

// Convert a CP437 encoded string by ptr to a UTF-8 encoded slice
extern "C" size_t cp437_string_ptr_to_utf8_slice(const void *ptr, char *utf8_slice)
{
  char *p = utf8_slice;
  const string *s = sp(ptr);

  const char *cp437_cstr = s->c_str();
  for (size_t i = 0; i < s->length(); i++)
  {
    uint8_t cp437_ch = static_cast<uint8_t>(cp437_cstr[i]);
    uint32_t utf8_len = cp437_to_utf8_table[cp437_ch * 2];
    uint32_t utf8_bytes = cp437_to_utf8_table[cp437_ch * 2 + 1];

    *(uint32_t *)(p) = utf8_bytes;
    p += utf8_len;
  }

  return static_cast<size_t>(p - utf8_slice);
}

// Convert a UTF-8 encoded slice to a single CP437 codepoint, 0 for not found
extern "C" uint8_t utf8_slice_to_cp437_codepoint(const char *ptr, size_t len)
{
  char buf[4] = {0};
  memcpy(buf, ptr, len);
  uint32_t utf8_bytes = *(uint32_t *)(buf);
  int left = 0;
  int right = 254;

  while (left <= right)
  {
    int mid = left + (right - left) / 2;
    uint32_t mid_val = utf8_to_cp437_bsearch_list[mid];

    if (mid_val == utf8_bytes)
    {
      return utf8_to_cp437_bsearch_result[mid];
    }
    else if (mid_val < utf8_bytes)
    {
      left = mid + 1;
    }
    else
    {
      right = mid - 1;
    }
  }

  return 0;
}
